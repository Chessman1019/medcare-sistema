-- Tabla para codigos de recuperacion de contrasena del portal MedCare.
-- Ejecutar en Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.codigos_recuperacion_contrasena (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  codigo_hash character varying NOT NULL,
  estado character varying NOT NULL DEFAULT 'ACTIVO',
  fecha_expiracion timestamp with time zone NOT NULL,
  fecha_uso timestamp with time zone,
  fecha_creacion timestamp with time zone NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'codigos_recuperacion_estado_check'
      AND conrelid = 'public.codigos_recuperacion_contrasena'::regclass
  ) THEN
    ALTER TABLE public.codigos_recuperacion_contrasena
      ADD CONSTRAINT codigos_recuperacion_estado_check
      CHECK (estado IN ('ACTIVO', 'USADO', 'EXPIRADO', 'CANCELADO'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_codigos_recuperacion_usuario_estado
  ON public.codigos_recuperacion_contrasena(usuario_id, estado);

CREATE INDEX IF NOT EXISTS idx_codigos_recuperacion_expiracion
  ON public.codigos_recuperacion_contrasena(fecha_expiracion);

ALTER TABLE public.codigos_recuperacion_contrasena ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'codigos_recuperacion_contrasena'
      AND policyname = 'codigos_recuperacion_dev_select'
  ) THEN
    CREATE POLICY codigos_recuperacion_dev_select
      ON public.codigos_recuperacion_contrasena
      FOR SELECT
      TO anon, authenticated
      USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'codigos_recuperacion_contrasena'
      AND policyname = 'codigos_recuperacion_dev_insert'
  ) THEN
    CREATE POLICY codigos_recuperacion_dev_insert
      ON public.codigos_recuperacion_contrasena
      FOR INSERT
      TO anon, authenticated
      WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'codigos_recuperacion_contrasena'
      AND policyname = 'codigos_recuperacion_dev_update'
  ) THEN
    CREATE POLICY codigos_recuperacion_dev_update
      ON public.codigos_recuperacion_contrasena
      FOR UPDATE
      TO anon, authenticated
      USING (true)
      WITH CHECK (true);
  END IF;
END $$;

GRANT SELECT, INSERT, UPDATE ON public.codigos_recuperacion_contrasena TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.codigos_recuperacion_contrasena_id_seq TO anon, authenticated, service_role;
