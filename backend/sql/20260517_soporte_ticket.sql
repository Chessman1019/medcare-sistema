-- Tabla independiente para solicitudes de soporte del portal MedCare.
-- Ejecutar en Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.soporte_ticket (
  id_ticket integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NULL REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  rol text NOT NULL,
  contexto text,
  mensaje text NOT NULL,
  id_cita integer NULL REFERENCES public.cita(id_cita) ON DELETE SET NULL,
  prioridad text NOT NULL DEFAULT 'normal',
  estado text NOT NULL DEFAULT 'abierto',
  respuesta text,
  asignado_a integer NULL REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
  fecha_actualizacion timestamp with time zone NOT NULL DEFAULT now(),
  cerrado_en timestamp with time zone
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'soporte_ticket_rol_check'
      AND conrelid = 'public.soporte_ticket'::regclass
  ) THEN
    ALTER TABLE public.soporte_ticket
      ADD CONSTRAINT soporte_ticket_rol_check
      CHECK (rol IN ('paciente', 'doctor', 'recepcionista', 'administrador'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'soporte_ticket_prioridad_check'
      AND conrelid = 'public.soporte_ticket'::regclass
  ) THEN
    ALTER TABLE public.soporte_ticket
      ADD CONSTRAINT soporte_ticket_prioridad_check
      CHECK (prioridad IN ('baja', 'normal', 'alta', 'urgente'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'soporte_ticket_estado_check'
      AND conrelid = 'public.soporte_ticket'::regclass
  ) THEN
    ALTER TABLE public.soporte_ticket
      ADD CONSTRAINT soporte_ticket_estado_check
      CHECK (estado IN ('abierto', 'en_revision', 'resuelto', 'cerrado'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_soporte_ticket_estado
  ON public.soporte_ticket(estado);

CREATE INDEX IF NOT EXISTS idx_soporte_ticket_usuario
  ON public.soporte_ticket(id_usuario);

CREATE INDEX IF NOT EXISTS idx_soporte_ticket_cita
  ON public.soporte_ticket(id_cita);

CREATE INDEX IF NOT EXISTS idx_soporte_ticket_fecha_actualizacion
  ON public.soporte_ticket(fecha_actualizacion DESC);

CREATE OR REPLACE FUNCTION public.set_soporte_ticket_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.fecha_actualizacion = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_soporte_ticket_updated_at ON public.soporte_ticket;
CREATE TRIGGER trg_soporte_ticket_updated_at
BEFORE UPDATE ON public.soporte_ticket
FOR EACH ROW
EXECUTE FUNCTION public.set_soporte_ticket_updated_at();

CREATE OR REPLACE VIEW public.v_soporte_ticket_detalle AS
SELECT
  st.id_ticket,
  st.id_usuario,
  st.rol,
  st.contexto,
  st.mensaje,
  st.id_cita,
  st.prioridad,
  st.estado,
  st.respuesta,
  st.asignado_a,
  st.fecha_creacion,
  st.fecha_actualizacion,
  st.cerrado_en,
  u.nombre AS usuario_nombre,
  u.apellido AS usuario_apellido,
  trim(concat(coalesce(u.nombre, ''), ' ', coalesce(u.apellido, ''))) AS solicitante,
  u.email AS usuario_email,
  u.telefono AS usuario_telefono,
  c.fecha_hora AS cita_fecha_hora,
  c.estado AS cita_estado,
  c.motivo AS cita_motivo,
  trim(concat(coalesce(pu.nombre, ''), ' ', coalesce(pu.apellido, ''))) AS paciente,
  trim(concat(coalesce(du.nombre, ''), ' ', coalesce(du.apellido, ''))) AS doctor
FROM public.soporte_ticket st
LEFT JOIN public.usuario u ON u.id_usuario = st.id_usuario
LEFT JOIN public.cita c ON c.id_cita = st.id_cita
LEFT JOIN public.usuario pu ON pu.id_usuario = c.id_paciente
LEFT JOIN public.usuario du ON du.id_usuario = c.id_doctor;

ALTER TABLE public.soporte_ticket DISABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE ON public.soporte_ticket TO anon, authenticated, service_role;
GRANT SELECT ON public.v_soporte_ticket_detalle TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.soporte_ticket_id_ticket_seq TO anon, authenticated, service_role;
